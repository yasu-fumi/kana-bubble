"""Embed the kana voice recordings into index.html for Kana Bubble.

Sources (WAV):
  五十音       C:/Users/rtrgd/Desktop/KANA_Voice/Voice/五十音   files named by romaji (KA.wav, SHI.wav, WO.wav, N.wav ...)
  濁音         C:/Users/rtrgd/Desktop/濁音                      files named by kana   (が_E4.wav ...)
  半濁音       C:/Users/rtrgd/Desktop/半濁音                    files named by kana   (ぱ_E4.wav ...)
  拗音         C:/Users/rtrgd/Desktop/拗音                      files named by kana   (きゃ_E4.wav ...)

Output: index.html, between the <!-- VOICES:BEGIN --> and <!-- VOICES:END --> markers:
        <script>window.KANA_BUBBLE_VOICES = { "か": "<base64 wav>", ... }</script>
The audio lives inside the page itself, so the voices work however the page is opened
(double-click, another browser, a preview pane) - nothing next to it can go missing.

Run again after changing any recording:  python build_voices.py
"""
import base64
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PAGE = os.path.join(HERE, 'index.html')
DESKTOP = r'C:\Users\rtrgd\Desktop'
GOJUON_DIR = os.path.join(DESKTOP, 'KANA_Voice', 'Voice', '五十音')
KANA_DIRS = [os.path.join(DESKTOP, '濁音'), os.path.join(DESKTOP, '半濁音'), os.path.join(DESKTOP, '拗音')]

ROMAJI_TO_KANA = {
    'A': 'あ', 'I': 'い', 'U': 'う', 'E': 'え', 'O': 'お',
    'KA': 'か', 'KI': 'き', 'KU': 'く', 'KE': 'け', 'KO': 'こ',
    'SA': 'さ', 'SHI': 'し', 'SU': 'す', 'SE': 'せ', 'SO': 'そ',
    'TA': 'た', 'CHI': 'ち', 'TSU': 'つ', 'TE': 'て', 'TO': 'と',
    'NA': 'な', 'NI': 'に', 'NU': 'ぬ', 'NE': 'ね', 'NO': 'の',
    'HA': 'は', 'HI': 'ひ', 'FU': 'ふ', 'HE': 'へ', 'HO': 'ほ',
    'MA': 'ま', 'MI': 'み', 'MU': 'む', 'ME': 'め', 'MO': 'も',
    'YA': 'や', 'YU': 'ゆ', 'YO': 'よ',
    'RA': 'ら', 'RI': 'り', 'RU': 'る', 'RE': 'れ', 'RO': 'ろ',
    'WA': 'わ', 'WO': 'を', 'N': 'ん',
}


def wav_files(folder):
    return sorted(f for f in os.listdir(folder) if f.lower().endswith('.wav'))


def b64(path):
    with open(path, 'rb') as f:
        return base64.b64encode(f.read()).decode('ascii')


voices = {}
for name in wav_files(GOJUON_DIR):
    stem = os.path.splitext(name)[0].upper()
    if stem not in ROMAJI_TO_KANA:
        raise SystemExit(f'unknown 五十音 file: {name}')
    voices[ROMAJI_TO_KANA[stem]] = b64(os.path.join(GOJUON_DIR, name))
for folder in KANA_DIRS:
    for name in wav_files(folder):
        kana = os.path.splitext(name)[0].split('_')[0]   # "きゃ_E4.wav" -> "きゃ"
        voices[kana] = b64(os.path.join(folder, name))

page = open(PAGE, encoding='utf-8').read()
block = ('<!-- VOICES:BEGIN (generated by build_voices.py - do not edit by hand) -->\n'
         '<script>window.KANA_BUBBLE_VOICES = ' + json.dumps(voices, ensure_ascii=False) + ';</script>\n'
         '<!-- VOICES:END -->')
page, n = re.subn(r'<!-- VOICES:BEGIN.*?<!-- VOICES:END -->', lambda m: block, page, flags=re.S)
if n != 1:
    raise SystemExit('VOICES markers not found in index.html')
open(PAGE, 'w', encoding='utf-8').write(page)

print(f'index.html: {len(voices)} voices embedded, page is now {os.path.getsize(PAGE) / 1e6:.1f} MB')
